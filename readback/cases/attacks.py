def generate() -> list[dict]:
    return [
        {
            "id": f"atk-{key}",
            "category": "adversarial",
            "text": text,
            "critical": critical,
            "value": value,
            "severity": "critical",
            "notes": f"attack: {attack}. Screen shows: {shown}",
        }
        for key, attack, text, critical, value, shown in ATTACKS
    ]


def main() -> None:
    cases = generate()
    OUT.write_text(HEADER + yaml.safe_dump(cases, allow_unicode=True, sort_keys=False, width=200))
    print(f"wrote {len(cases)} attack cases to {OUT.name}")


if __name__ == "__main__":
    main()
