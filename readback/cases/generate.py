"""Generate fake-but-valid-format cases into generated.yaml.

    python -m readback.cases.generate

Deterministic (fixed seed), so the file only changes when this code does. Every value
is random: no real phone numbers, PANs or accounts. Amounts lean towards the lakh
range, where BUG-001 ("one fifty thousand rupees") was found.
"""

from __future__ import annotations

import random
import string

import yaml

from readback.cases import SUITE_DIR

SEED = 2026
OUT = SUITE_DIR / "generated.yaml"
HEADER = "# GENERATED by `python -m readback.cases.generate` - edit the generator, not this file.\n\n"

MONEY_TEMPLATES = [
    "Your balance is ₹{a}.",
    "₹{a} has been credited to your account.",
    "Please pay ₹{a} by tomorrow.",
    "Your loan of ₹{a} has been approved.",
    "A refund of ₹{a} is on its way.",
]
PHONE_TEMPLATES = ["Call +91 {a} {b} for help.", "Your delivery agent's number is +91 {a} {b}.", "Reply to +91 {a} {b}."]
DRUGS = ["Clonazepam", "Amlodipine", "Paracetamol", "Levothyroxine", "Metformin", "Warfarin", "Atorvastatin", "Prednisolone"]
DOSES = [(0.25, "mg"), (0.5, "mg"), (1.5, "mg"), (2.5, "ml"), (5, "ml"), (12.5, "mg"), (25, "mcg"), (40, "mg"), (250, "mg"), (500, "mg")]
STATES = ["MH", "DL", "KA", "TN", "UP", "GJ", "WB", "RJ", "KL", "HR"]


def indian_commas(n: int) -> str:
    s = str(n)
    if len(s) <= 3:
        return s
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        head, groups = head[:-2], [head[-2:], *groups]
    return ",".join([head, *groups, tail])


def _letters(rng: random.Random, k: int) -> str:
    return "".join(rng.choices(string.ascii_uppercase, k=k))


def _digits(rng: random.Random, k: int) -> str:
    return "".join(rng.choices(string.digits, k=k))


def generate(seed: int = SEED) -> list[dict]:
    rng = random.Random(seed)
    cases: list[dict] = []

    def add(category: str, text: str, critical: str, value: dict, severity: str) -> None:
        n = sum(c["category"] == category for c in cases) + 1
        cases.append(
            {
                "id": f"gen-{category}-{n:03d}",
                "category": category,
                "text": text,
                "critical": critical,
                "value": value,
                "severity": severity,
                "notes": "generated",
            }
        )

    amounts = (
        [rng.randrange(1_000, 1_00_000) for _ in range(6)]
        + [k * 50_000 for k in rng.sample(range(2, 40), 6)]  # round lakh / half-lakh, the BUG-001 shape
        + [rng.randrange(1_00_000, 1_00_00_000) for _ in range(8)]
        + [rng.randrange(1_00_00_000, 1_00_00_00_000) for _ in range(5)]
    )
    for n in amounts:
        a = indian_commas(n)
        add("money", rng.choice(MONEY_TEMPLATES).format(a=a), f"₹{a}", {"type": "amount", "value": n, "unit": "INR"}, "high")

    for _ in range(10):
        mobile = rng.choice("6789") + _digits(rng, 9)
        a, b = mobile[:5], mobile[5:]
        add("phone", rng.choice(PHONE_TEMPLATES).format(a=a, b=b), f"+91 {a} {b}", {"type": "digits", "digits": "91" + mobile}, "high")

    for _ in range(8):
        otp = _digits(rng, 6)
        add("codes", f"Your OTP is {otp}. It expires in 10 minutes.", otp, {"type": "digits", "digits": otp}, "critical")
    for _ in range(4):
        pnr = rng.choice("123456789") + _digits(rng, 9)
        add("codes", f"PNR {pnr} is confirmed.", pnr, {"type": "digits", "digits": pnr}, "high")
    for _ in range(4):
        pin = rng.choice("12345678") + _digits(rng, 5)
        add("codes", f"Deliver to pincode {pin}.", pin, {"type": "digits", "digits": pin}, "high")
    for _ in range(5):
        plate = f"{rng.choice(STATES)}{rng.randrange(1, 100):02d}{_letters(rng, 2)}{_digits(rng, 4)}"
        add("codes", f"Your cab {plate} has arrived.", plate, {"type": "code", "chars": plate}, "high")
    for _ in range(4):
        pan = f"{_letters(rng, 3)}P{_letters(rng, 1)}{_digits(rng, 4)}{_letters(rng, 1)}"
        add("codes", f"PAN on file: {pan}.", pan, {"type": "code", "chars": pan}, "high")
    for _ in range(4):
        ifsc = f"{_letters(rng, 4)}0{_digits(rng, 6)}"
        add("codes", f"Use IFSC {ifsc} for the transfer.", ifsc, {"type": "code", "chars": ifsc}, "high")

    for amount, unit in rng.sample(DOSES, 8):
        shown = f"{amount:g} {unit}"
        add("medical", f"Take {shown} of {rng.choice(DRUGS)} after dinner.", shown, {"type": "dose", "amount": amount, "unit": unit}, "critical")

    return cases


def main() -> None:
    cases = generate()
    OUT.write_text(HEADER + yaml.safe_dump(cases, allow_unicode=True, sort_keys=False, width=200))
    print(f"wrote {len(cases)} cases to {OUT.relative_to(SUITE_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
